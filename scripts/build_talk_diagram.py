"""Copy the AWS deployment diagram into slide 4 of the public talk.

docs/aws-deployment.html is the one source of the diagram. This script takes its
<svg id="deployment">, switches it to the dark deck theme with the canvas and brand
lines hidden (the deck has its own), and writes it between the aws-diagram markers in
src/mel/explorer/talk/index.html. It also copies the icons the SVG uses into
src/mel/explorer/talk/aws-icons/, because /talk serves only that folder.

    uv run python scripts/build_talk_diagram.py
"""

import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "aws-deployment.html"
ICONS = ROOT / "docs" / "assets" / "aws-icons"
TALK = ROOT / "src" / "mel" / "explorer" / "talk"
START = "<!-- aws-diagram:start (generated by scripts/build_talk_diagram.py; edit docs/aws-deployment.html) -->"
END = "<!-- aws-diagram:end -->"


def embedded_svg(source_html: str) -> str:
    """The talk's copy of the diagram: dark theme, no canvas, icons from talk/aws-icons/."""
    found = re.search(r'<svg id="deployment".*?</svg>', source_html, re.S)
    if not found:
        raise SystemExit(f'No <svg id="deployment"> in {SOURCE}')
    svg = found.group(0).replace('<svg id="deployment"', '<svg id="deployment" class="ad-dark ad-embed"', 1)
    return svg.replace('href="assets/aws-icons/', 'href="aws-icons/')


def icon_names(svg: str) -> list[str]:
    return sorted(set(re.findall(r'href="aws-icons/([^"]+)"', svg)))


def splice(page: str, svg: str) -> str:
    start, end = page.find(START), page.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"Missing aws-diagram markers in {TALK / 'index.html'}")
    return page[: start + len(START)] + "\n" + svg + "\n" + page[end:]


def main() -> None:
    svg = embedded_svg(SOURCE.read_text(encoding="utf-8"))
    names = icon_names(svg)
    target = TALK / "aws-icons"
    target.mkdir(exist_ok=True)
    for old in target.glob("*.svg"):
        if old.name not in names:
            old.unlink()
    for name in names:
        shutil.copyfile(ICONS / name, target / name)
    index = TALK / "index.html"
    index.write_text(splice(index.read_text(encoding="utf-8"), svg), encoding="utf-8")
    print(f"Wrote slide 4 and {len(names)} icons to {TALK.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
